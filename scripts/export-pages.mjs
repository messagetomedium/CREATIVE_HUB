import { cp, mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = path.join(root, 'site');
const entry = path.join(root, 'index.html');
const marker = 'Creative Factory static Pages entry point; generated by npm run export:pages.';
const projectBase = process.env.PAGES_BASE_PATH ?? '/CREATIVE_HUB/';
if (!/^\/(?:[A-Za-z0-9_-]+\/)*$/.test(projectBase)) {
  throw new Error('PAGES_BASE_PATH must be / or a safe directory path ending in /.');
}

async function exists(file) {
  try {
    await stat(file);
    return true;
  } catch (error) {
    if (error.code === 'ENOENT') return false;
    throw error;
  }
}
// Only replace this script's own generated output, never a user's existing homepage.
if (await exists(entry)) {
  if (!(await readFile(entry, 'utf8')).includes(marker))
    throw new Error('Existing root index.html is not a managed Pages export.');
}
if (await exists(output)) {
  const saved = JSON.parse(await readFile(path.join(output, 'export.json'), 'utf8'));
  if (saved.generator !== 'creative-factory-pages-export-v1')
    throw new Error('Existing site directory is not a managed Pages export.');
}
const npmCli = process.env.npm_execpath;
if (!npmCli) throw new Error('Run this script through npm run export:pages.');
const releaseBase = projectBase + 'site/';
const build = spawnSync(process.execPath, [npmCli, 'run', 'build'], {
  cwd: root,
  stdio: 'inherit',
  env: { ...process.env, VITE_BASE_PATH: releaseBase },
});
if (build.status !== 0) process.exit(build.status ?? 1);

const dist = path.join(root, 'apps/web/dist');
const html = await readFile(path.join(dist, 'index.html'), 'utf8');
if (!html.includes('id="root"') || !html.includes(releaseBase + 'assets/')) {
  throw new Error('Build output does not contain the application entry and expected base path.');
}
await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
await cp(dist, output, { recursive: true });
await writeFile(
  path.join(output, 'export.json'),
  JSON.stringify(
    {
      generator: 'creative-factory-pages-export-v1',
      projectBase,
      releaseBase,
    },
    null,
    2,
  ) + '\n',
);
// Both /CREATIVE_HUB/ and /CREATIVE_HUB/site/ boot the same app; no redirect is needed.
await writeFile(entry, `<!-- ${marker} -->\n${html}`);
await writeFile(path.join(root, '.nojekyll'), '');
// Use the same directory layout for Actions and branch publishing, so either
// deployment mode serves an application with the same asset URLs.
const artifact = path.join(root, 'dist/pages');
await rm(artifact, { recursive: true, force: true });
await mkdir(artifact, { recursive: true });
await cp(output, path.join(artifact, 'site'), { recursive: true });
await cp(entry, path.join(artifact, 'index.html'));
await writeFile(path.join(artifact, '.nojekyll'), '');
console.log(`Branch Pages export ready: index.html + site/, base ${releaseBase}`);
