export function templateModes(
  t: (typeof SOURCE_TEMPLATES)[number],
): (keyof typeof ARTIST_VIEW_MODES)[] {
  if (t.id === 'eyes' || t.id === 'mouth') return ['front'];
  if (t.id === 'details') return ['sym1', 'sym2', 'full'];
  if (t.id === 'shoe') return ['pair'];
  return ['full', 'pair'];
}
export type SourceTemplate = (typeof SOURCE_TEMPLATES)[number];
export function templateDescriptor(template: SourceTemplate, slot = 1) {
  return PartEntrySchema.parse({
    id: `character-${template.id}-${slot}`,
    source: `/content/character-${template.id}-${slot}.png`,
    parent: template.parent,
    pass: 'front',
    material: template.material,
    frameWidth: template.width,
    frameHeight: template.height,
    anchor: template.anchor,
    offset: { x: 0, y: 0 },
    fit: template.fit,
    referenceWidth: template.referenceWidth,
    mirrorWest: false,
    sync: template.parent === 'head' ? 'head' : template.fit === 'limb' ? 'limb' : 'body',
    hideBase: template.id === 'shoe' || template.id === 'glove',
    selection: { field: template.field, slot },
  });
}

export function templateFolder(t: SourceTemplate) {
  return t.id === 'details' ? 'DETAILS' : t.category.toUpperCase();
}
