export type SourceTemplate = (typeof SOURCE_TEMPLATES)[number];
export function templateDescriptor(template: SourceTemplate, slot = 1) {
  return PartEntrySchema.parse({
    id: `artist-${template.id}-${slot}`,
    source: `/content/artist-${template.id}-${slot}.png`,
    parent: template.parent,
    pass: 'front',
    material: template.material,
    frameWidth: template.width,
    frameHeight: template.height,
    anchor: template.anchor,
    offset: { x: 0, y: 0 },
    fit: template.fit,
    referenceWidth: 'referenceWidth' in template ? template.referenceWidth : undefined,
    mirrorWest: true,
    sync: template.parent === 'head' ? 'head' : template.fit === 'limb' ? 'limb' : 'body',
    selection: { field: template.field, slot },
  });
}
